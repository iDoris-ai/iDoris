-- 0005：补贴池一个账期里的消耗要读「结算时刻落在这个账期里的 `settle`」。
--
-- 旧格式（v0.5.0 / main）把没迟到的结算里超出预留的部分和预留之内的部分一起记在一条 `settle` 里，归属时刻是预留创建的时刻；
-- 超出的部分按 owner 的决定归属**结算的时刻**（担保人吸收它读的是结算那一刻的额度），所以一个账期的消耗里，除了「预留的时刻
-- （`window_at_ms`）在账期里」的分录，还有「预留在上个账期、结算在这个账期」的 `settle`。前一个方向有 `ledger_entries_by_account_window`；
-- 后一个方向原来没有索引，只能把这个池账户的全部历史读一遍（池账户上有所有成员的每一笔花费）。这条部分索引只收 `settle`，
-- 让两个方向各走一个索引（Codex 四复审 Low）。
--
-- 只加索引：没有新的列、表、触发器，不改写任何一行。旧版本的二进制只登记、只应用自己认识的迁移，认不得第 5 号也不要紧：
-- 它们照常读写这个库，这条索引由 SQLite 自己维护（对它们是多出来的、不会被用到的索引）。
CREATE INDEX ledger_entries_settled_by_account_at ON ledger_entries (account_id, at_ms) WHERE kind = 'settle';
