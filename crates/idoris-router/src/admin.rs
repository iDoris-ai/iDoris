/// Snapshot startup-validated backend configuration and local lifecycle
/// bindings only. This deliberately does not probe runtime health, models,
/// memory pressure, or network reachability.
pub fn backends(state: &AppState) -> Vec<AdminBackend> {
    state
        .cards
        .iter()
        .map(|card| AdminBackend {
            provider_id: card.provider.id.clone(),
            locality: card.provider.locality,
            form: card.form,
            lifecycle_runtime_bound: state.runtimes.get(&card.provider.id).is_some(),
        })
        .collect()
}

/// Snapshot the stable public role contract only. The aliases are accepted
/// model=idoris/<role> request names; they do not claim any configured or
/// currently available model serves the role.
pub fn roles() -> Vec<AdminRole> {
    ROLES
        .iter()
        .copied()
        .map(|role| AdminRole {
            role: role.as_str(),
            aliases: vec![format!("idoris/{}", role.as_str())],
            catalog_role: role.is_catalog_role(),
        })
        .collect()
}

/// Observe each active model source without collapsing failures into an
/// apparently complete flat list. HTTP model ids are runtime observations;
/// subscription ids are registration facts, not backend health claims.
pub async fn models(state: &AppState) -> AdminModelsSnapshot {
    let mut sources = Vec::new();
    for card in &state.cards {
        if card.form != idoris_contracts::component_card::Form::HttpService {
            continue;
        }
        let (state_kind, models, error) =
            match crate::models::observe_http_models(&state.http_client, card).await {
                Ok(crate::models::HttpModelObservation::Observed(entries)) => (
                    AdminModelSourceState::Observed,
                    entries.into_iter().map(|entry| entry.id).collect(),
                    None,
                ),
                Ok(crate::models::HttpModelObservation::Unavailable) => (
                    AdminModelSourceState::Error,
                    Vec::new(),
                    Some(AdminModelSourceError::Unavailable),
                ),
                Err(crate::models::ModelsError::UpstreamAuthenticationFailed { .. }) => (
                    AdminModelSourceState::Error,
                    Vec::new(),
                    Some(AdminModelSourceError::AuthenticationFailed),
                ),
            };
        sources.push(AdminModelSource {
            provider_id: card.provider.id.clone(),
            source: AdminModelSourceKind::HttpModelsEndpoint,
            state: state_kind,
            models,
            error,
        });
    }
    sources.extend(
        state
            .subscriptions
            .discovery()
            .into_iter()
            .map(|entry| AdminModelSource {
                provider_id: entry.provider_id,
                source: AdminModelSourceKind::SubscriptionRegistration,
                state: AdminModelSourceState::Configured,
                models: vec![entry.model_id],
                error: None,
            }),
    );
    AdminModelsSnapshot { sources }
}

/// Observe only lifecycle-managed runtimes. Resident direct HTTP cards are
/// intentionally absent because they do not have a `RuntimeRegistry` entry.
/// Backend failures are represented by `state=error`; free-form backend error
/// strings never become part of this management snapshot.
pub async fn runtimes(state: &AppState) -> AdminRuntimesSnapshot {
    let runtimes = state
        .runtimes
        .status_observations()
        .await
        .into_iter()
        .map(|(provider_id, status)| map_runtime_status(provider_id, status))
        .collect();
    AdminRuntimesSnapshot { runtimes }
}

fn map_runtime_status(
    provider_id: String,
    status: Result<idoris_backend::BackendStatus, idoris_backend::BackendError>,
) -> AdminRuntime {
    match status {
        Ok(status) => AdminRuntime {
            provider_id,
            state: AdminRuntimeState::Observed,
            pressure: Some(status.pressure),
            used_gb: Some(status.used_gb),
            model_memory_max_gb: Some(status.model_memory_max_gb),
            loaded: Some(status.loaded),
        },
        Err(_) => AdminRuntime {
            provider_id,
            state: AdminRuntimeState::Error,
            pressure: None,
            used_gb: None,
            model_memory_max_gb: None,
            loaded: None,
        },
    }
}

/// Snapshot the already-installed capacity provider without inventing a
/// fallback. Successful empty capacity is distinct from an unavailable
/// provider, and provider errors never expose free-form backend detail.
pub async fn capacity(state: &AppState) -> AdminCapacitySnapshot {
    let Some(provider) = &state.capabilities else {
        return AdminCapacitySnapshot {
            state: AdminCapacityState::Unavailable,
            entries: None,
        };
    };
    match provider.snapshot().await {
        Ok(entries)
            if entries.iter().any(|entry| {
                !entry.estimated_memory_gb.is_finite() || entry.estimated_memory_gb < 0.0
            }) =>
        {
            AdminCapacitySnapshot {
                state: AdminCapacityState::Error,
                entries: None,
            }
        }
        Ok(entries) => AdminCapacitySnapshot {
            state: AdminCapacityState::Observed,
            entries: Some(
                entries
                    .into_iter()
                    .map(|entry| AdminCapacityEntry {
                        id: entry.id,
                        capability: entry.capability,
                        resident: entry.resident,
                        estimated_memory_gb: entry.estimated_memory_gb,
                        ctx_limit: entry.ctx_limit,
                        queue_depth: entry.queue_depth,
                        admission_status: match entry.admission_status {
                            crate::capabilities::AdmissionStatus::Ready => {
                                AdminAdmissionStatus::Ready
                            }
                            crate::capabilities::AdmissionStatus::RequiresEviction => {
                                AdminAdmissionStatus::RequiresEviction
                            }
                            crate::capabilities::AdmissionStatus::Blocked => {
                                AdminAdmissionStatus::Blocked
                            }
                        },
                    })
                    .collect(),
            ),
        },
        Err(_) => AdminCapacitySnapshot {
            state: AdminCapacityState::Error,
            entries: None,
        },
    }
}

