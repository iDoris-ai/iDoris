pub const ADMIN_PORT_ENV: &str = "IDORIS_ADMIN_PORT";
pub const DEFAULT_ADMIN_PORT: u16 = 8741;
pub const ADMIN_BIND_HOST: std::net::Ipv4Addr = std::net::Ipv4Addr::LOCALHOST;

const SESSION_TOKEN_LEN: usize = 64;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdminPortError(String);

impl std::fmt::Display for AdminPortError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for AdminPortError {}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AdminBindConfig {
    port: u16,
}

impl AdminBindConfig {
    /// Parse the dedicated Admin listener port. Unset/blank uses the public
    /// Admin default; explicit values must be plain decimal TCP ports.
    pub fn parse(raw: Option<&str>) -> Result<Self, AdminPortError> {
        let raw = match raw.map(str::trim) {
            None | Some("") => {
                return Ok(Self {
                    port: DEFAULT_ADMIN_PORT,
                });
            }
            Some(raw) => raw,
        };
        if !raw.bytes().all(|byte| byte.is_ascii_digit()) {
            return Err(AdminPortError(format!(
                "{ADMIN_PORT_ENV} 不是合法的端口号：'{raw}'。请设置为 1-65535 之间的整数"
            )));
        }
        let port: u64 = raw.parse().map_err(|_| {
            AdminPortError(format!(
                "{ADMIN_PORT_ENV} 不是合法的端口号：'{raw}'。请设置为 1-65535 之间的整数"
            ))
        })?;
        if !(1..=u16::MAX as u64).contains(&port) {
            return Err(AdminPortError(format!(
                "{ADMIN_PORT_ENV} 不是合法的端口号：'{raw}'。请设置为 1-65535 之间的整数"
            )));
        }
        Ok(Self { port: port as u16 })
    }

    pub fn port(self) -> u16 {
        self.port
    }

    pub fn addr(self) -> std::net::SocketAddr {
        std::net::SocketAddr::from((ADMIN_BIND_HOST, self.port))
    }

    pub async fn bind(self) -> std::io::Result<tokio::net::TcpListener> {
        tokio::net::TcpListener::bind(self.addr()).await
    }
}

pub struct AdminSessionToken(String);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AdminTokenError;

impl std::fmt::Display for AdminTokenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Admin session token 必须是 64 位小写十六进制字符串")
    }
}

impl std::error::Error for AdminTokenError {}

impl AdminSessionToken {
    pub fn mint() -> Self {
        Self(format!(
            "{}{}",
            Uuid::new_v4().simple(),
            Uuid::new_v4().simple()
        ))
    }

    /// Explicit one-time exposure for delivering the token to the local
    /// management client. Never log or persist this value.
    pub fn expose_secret(&self) -> &str {
        &self.0
    }

    /// Accept a token generated by a trusted local launcher. The launcher must
    /// generate all 64 hex digits from a cryptographically secure random
    /// source. It may retain the same secret in process memory for Admin
    /// requests; callers must not put it in argv, environment variables, logs,
    /// or files.
    pub fn from_launcher_secret(secret: &[u8]) -> Result<Self, AdminTokenError> {
        if secret.len() != SESSION_TOKEN_LEN
            || !secret
                .iter()
                .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
        {
            return Err(AdminTokenError);
        }
        let secret = std::str::from_utf8(secret).map_err(|_| AdminTokenError)?;
        Ok(Self(secret.to_owned()))
    }

    pub fn matches(&self, candidate: &str) -> bool {
        if candidate.len() != SESSION_TOKEN_LEN {
            return false;
        }
        bool::from(self.0.as_bytes().ct_eq(candidate.as_bytes()))
    }
}

impl std::fmt::Debug for AdminSessionToken {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("AdminSessionToken([REDACTED])")
    }
}

impl std::fmt::Display for AdminSessionToken {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("[REDACTED]")
    }
}

#[derive(Clone)]
struct AdminHttpState {
    app: Arc<AppState>,
    token: Arc<AdminSessionToken>,
}

/// Build the Admin listener router. Its static console shell carries no privileged
/// data; every `/admin/api/v1/*` resource remains bearer-authenticated. The caller
/// owns the separate loopback listener; this router is never mounted on [`crate::build_app`].
pub fn build_admin_app(state: AppState, token: AdminSessionToken) -> Router {
    let state = AdminHttpState {
        app: Arc::new(state),
        token: Arc::new(token),
    };
    let api = Router::new()
        .route("/status", get(admin_status))
        .route("/backends", get(admin_backends))
        .route("/models", get(admin_models))
        .route("/roles", get(admin_roles))
        .route("/runtimes", get(admin_runtimes))
        .fallback(StatusCode::NOT_FOUND)
        .layer(middleware::from_fn_with_state(
            state.clone(),
            require_admin_auth,
        ))
        .with_state(state);

    Router::new()
        .route("/admin/", get(admin_console))
        .nest("/admin/api/v1", api)
        .fallback(StatusCode::NOT_FOUND)
}

